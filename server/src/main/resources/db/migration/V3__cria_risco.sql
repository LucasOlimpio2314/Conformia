-- Registro de riscos (ISO 27001 6.1.2 avaliação, 6.1.3 tratamento, 8.2).
-- Catálogos: ameaças e vulnerabilidades (crescem pelo sistema) e controles do Anexo A (fixos).
-- Risco nunca é apagado: é encerrado com justificativa.

-- ---------- catálogos que o usuário pode ampliar ----------
CREATE TABLE ameaca (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150) NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    criado_por_id BIGINT       REFERENCES usuario (id)   -- NULL = item inicial da migration
);
-- "Phishing" e "phishing" são o mesmo item
CREATE UNIQUE INDEX uk_ameaca_nome ON ameaca (lower(nome));

CREATE TABLE vulnerabilidade (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(150) NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    criado_por_id BIGINT       REFERENCES usuario (id)
);
CREATE UNIQUE INDEX uk_vulnerabilidade_nome ON vulnerabilidade (lower(nome));

