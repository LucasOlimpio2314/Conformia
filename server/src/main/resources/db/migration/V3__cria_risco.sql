-- ---------- risco ----------
CREATE SEQUENCE risco_codigo_seq;

CREATE TABLE risco (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo             VARCHAR(12)   NOT NULL,
    titulo             VARCHAR(200)  NOT NULL,
    cenario            VARCHAR(2000),
    ameaca_id          BIGINT        NOT NULL REFERENCES ameaca (id),
    vulnerabilidade_id BIGINT        NOT NULL REFERENCES vulnerabilidade (id),
    -- dono do risco (6.1.2 c 2): Gerente ou Analista
    dono_id            BIGINT        NOT NULL REFERENCES usuario (id),
    -- risco inerente: nível = probabilidade x impacto (calculado, não gravado)
    probabilidade      INTEGER       NOT NULL CHECK (probabilidade BETWEEN 1 AND 5),
    impacto            INTEGER       NOT NULL CHECK (impacto BETWEEN 1 AND 5),
    -- NULL = "a definir"
    tratamento         VARCHAR(20)   CHECK (tratamento IN ('MITIGAR', 'ACEITAR', 'TRANSFERIR', 'EVITAR')),
    situacao           VARCHAR(20)   NOT NULL DEFAULT 'ATIVO' CHECK (situacao IN ('ATIVO', 'ENCERRADO')),
    justificativa_encerramento VARCHAR(500),
    encerrado_em       TIMESTAMPTZ,
    criado_em          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    criado_por_id      BIGINT        NOT NULL REFERENCES usuario (id),
    atualizado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_por_id  BIGINT        NOT NULL REFERENCES usuario (id),

    CONSTRAINT uk_risco_codigo UNIQUE (codigo),
    CONSTRAINT ck_risco_encerrado CHECK (situacao = 'ATIVO' OR justificativa_encerramento IS NOT NULL)
);

-- um risco afeta um ou mais ativos
CREATE TABLE risco_ativo (
    risco_id BIGINT NOT NULL REFERENCES risco (id),
    ativo_id BIGINT NOT NULL REFERENCES ativo (id),
    PRIMARY KEY (risco_id, ativo_id)
);
CREATE INDEX ix_risco_ativo_ativo ON risco_ativo (ativo_id);

-- controles do Anexo A relacionados ao risco (pelo menos um, regra no service)
CREATE TABLE risco_controle (
    risco_id        BIGINT     NOT NULL REFERENCES risco (id),
    controle_codigo VARCHAR(5) NOT NULL REFERENCES controle_anexo_a (codigo),
    PRIMARY KEY (risco_id, controle_codigo)
);
