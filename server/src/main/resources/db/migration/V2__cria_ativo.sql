-- Inventário de ativos (ISO 27001 A.5.9) com classificação (A.5.12) e criticidade C-I-D.
-- Ativo nunca é apagado: é descontinuado com justificativa (histórico para auditoria).

-- Gera o número do código legível (ATV-001, ATV-002...). Sequência não repete
-- nem com dois cadastros ao mesmo tempo.
CREATE SEQUENCE ativo_codigo_seq;

CREATE TABLE ativo (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(12)  NOT NULL,
    nome              VARCHAR(150) NOT NULL,
    tipo              VARCHAR(30)  NOT NULL,
    descricao         VARCHAR(1000),
    localizacao       VARCHAR(150),
    -- dono do ativo: sempre um usuário interno (GERENTE ou ANALISTA), mesmo se terceirizado (A.5.23)
    proprietario_id   BIGINT       NOT NULL REFERENCES usuario (id),
    terceirizado      BOOLEAN      NOT NULL DEFAULT FALSE,
    fornecedor        VARCHAR(120),
    classificacao     VARCHAR(20)  NOT NULL,
    -- notas de 1 a 5 (mesma escala do impacto na matriz de risco 5x5)
    confidencialidade INTEGER      NOT NULL,
    integridade       INTEGER      NOT NULL,
    disponibilidade   INTEGER      NOT NULL,
    situacao          VARCHAR(20)  NOT NULL DEFAULT 'EM_USO',
    justificativa_descontinuacao VARCHAR(500),
    descontinuado_em  TIMESTAMPTZ,
    criado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    criado_por_id     BIGINT       NOT NULL REFERENCES usuario (id),
    atualizado_em     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    atualizado_por_id BIGINT       NOT NULL REFERENCES usuario (id),

    CONSTRAINT uk_ativo_codigo UNIQUE (codigo),
    CONSTRAINT ck_ativo_tipo CHECK (tipo IN ('INFORMACAO', 'PROCESSO', 'SOFTWARE', 'HARDWARE', 'REDE',
                                             'SERVICO_TERCEIRO', 'PESSOAS', 'INSTALACAO')),
    CONSTRAINT ck_ativo_classificacao CHECK (classificacao IN ('PUBLICA', 'INTERNA', 'CONFIDENCIAL', 'RESTRITA')),
    CONSTRAINT ck_ativo_situacao CHECK (situacao IN ('EM_USO', 'DESCONTINUADO')),
    CONSTRAINT ck_ativo_cid CHECK (confidencialidade BETWEEN 1 AND 5
                                   AND integridade BETWEEN 1 AND 5
                                   AND disponibilidade BETWEEN 1 AND 5),
    -- terceirizado exige fornecedor
    CONSTRAINT ck_ativo_fornecedor CHECK (terceirizado = FALSE OR fornecedor IS NOT NULL),
    -- descontinuado exige justificativa
    CONSTRAINT ck_ativo_descontinuado CHECK (situacao = 'EM_USO' OR justificativa_descontinuacao IS NOT NULL)
);

-- busca de "ativos deste proprietário" (aviso de proprietário inativo, futuros relatórios)
CREATE INDEX ix_ativo_proprietario ON ativo (proprietario_id);
