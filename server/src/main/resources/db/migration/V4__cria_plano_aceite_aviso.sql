-- Plano de ação, risco residual, aceite formal (ISO 27001 6.1.3 e/f, 8.3) e avisos.

-- ---------- risco residual esperado (definido no plano de ação) ----------
ALTER TABLE risco
    ADD COLUMN probabilidade_residual INTEGER CHECK (probabilidade_residual BETWEEN 1 AND 5),
    ADD COLUMN impacto_residual       INTEGER CHECK (impacto_residual BETWEEN 1 AND 5),
    -- os dois juntos: ou o residual está definido, ou não está
    ADD CONSTRAINT ck_risco_residual CHECK ((probabilidade_residual IS NULL) = (impacto_residual IS NULL));

-- ---------- ações do plano ----------
CREATE SEQUENCE acao_codigo_seq;

CREATE TABLE acao_plano (
    id                BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(12)   NOT NULL,
    risco_id          BIGINT        NOT NULL REFERENCES risco (id),
    titulo            VARCHAR(200)  NOT NULL,
    responsavel_id    BIGINT        NOT NULL REFERENCES usuario (id),
    prazo             DATE          NOT NULL,
    controle_codigo   VARCHAR(5)    NOT NULL REFERENCES controle_anexo_a (codigo),
    situacao          VARCHAR(20)   NOT NULL DEFAULT 'PENDENTE'
                      CHECK (situacao IN ('PENDENTE', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    -- o que comprova a ação: nº de chamado, link, documento
    evidencia         VARCHAR(1000),
    finalizada_em     TIMESTAMPTZ,
    criado_em         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    criado_por_id     BIGINT        NOT NULL REFERENCES usuario (id),
    atualizado_em     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_por_id BIGINT        NOT NULL REFERENCES usuario (id),

    CONSTRAINT uk_acao_codigo UNIQUE (codigo),
    -- concluir exige evidência
    CONSTRAINT ck_acao_evidencia CHECK (situacao <> 'CONCLUIDA' OR evidencia IS NOT NULL)
);
CREATE INDEX ix_acao_risco ON acao_plano (risco_id);

-- ---------- aceite formal (Gerente) ----------
CREATE TABLE aceite_risco (
    id                  BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risco_id            BIGINT        NOT NULL REFERENCES risco (id),
    -- RISCO: tratamento "Aceitar"; RESIDUAL: o que sobra depois do plano de ação
    tipo                VARCHAR(20)   NOT NULL CHECK (tipo IN ('RISCO', 'RESIDUAL')),
    -- nível aceito naquele momento (foto: o risco pode mudar depois)
    probabilidade       INTEGER       NOT NULL CHECK (probabilidade BETWEEN 1 AND 5),
    impacto             INTEGER       NOT NULL CHECK (impacto BETWEEN 1 AND 5),
    justificativa       VARCHAR(1000) NOT NULL,
    condicoes           VARCHAR(1000),
    aceito_por_id       BIGINT        NOT NULL REFERENCES usuario (id),
    aceito_em           TIMESTAMPTZ   NOT NULL,
    valido_ate          TIMESTAMPTZ   NOT NULL,
    situacao            VARCHAR(20)   NOT NULL DEFAULT 'VIGENTE'
                        CHECK (situacao IN ('VIGENTE', 'VENCIDO', 'REVOGADO', 'INVALIDADO')),
    -- quando e por que deixou de valer (vencido, revogado ou invalidado)
    encerrado_em        TIMESTAMPTZ,
    encerrado_por_id    BIGINT        REFERENCES usuario (id),   -- NULL = sistema (vencimento)
    motivo_encerramento VARCHAR(500),

    CONSTRAINT ck_aceite_encerrado CHECK (situacao = 'VIGENTE' OR motivo_encerramento IS NOT NULL)
);
-- no máximo UM aceite vigente por risco (índice único parcial)
CREATE UNIQUE INDEX uk_aceite_vigente ON aceite_risco (risco_id) WHERE situacao = 'VIGENTE';

-- ---------- avisos dentro do sistema ----------
CREATE TABLE aviso (
    id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_id BIGINT        NOT NULL REFERENCES usuario (id),
    tipo            VARCHAR(30)   NOT NULL
                    CHECK (tipo IN ('ACEITE_INVALIDADO', 'ACEITE_VENCIDO', 'RESIDUAL_PRONTO')),
    titulo          VARCHAR(200)  NOT NULL,
    mensagem        VARCHAR(1000) NOT NULL,
    link            VARCHAR(200)  NOT NULL,
    criado_em       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    lido_em         TIMESTAMPTZ
);
CREATE INDEX ix_aviso_destinatario ON aviso (destinatario_id, lido_em);
