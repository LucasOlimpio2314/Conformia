-- Usuários do sistema. A senha nunca é guardada: só o hash BCrypt.

-- pgcrypto fornece crypt()/gen_salt('bf') para gerar o hash BCrypt do usuário inicial
-- no próprio SQL. É uma extensão "trusted" (PostgreSQL 13+): o dono do banco pode criar.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE usuario (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(120) NOT NULL,
    email            VARCHAR(160) NOT NULL,
    senha_hash       VARCHAR(100) NOT NULL,
    perfil           VARCHAR(20)  NOT NULL,
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    -- TRUE enquanto a pessoa não trocar a senha gerada pelo sistema
    senha_temporaria BOOLEAN      NOT NULL DEFAULT TRUE,
    -- prazo da senha temporária; NULL = sem prazo (usuário inicial)
    senha_expira_em  TIMESTAMPTZ,
    ultimo_acesso    TIMESTAMPTZ,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_email_minusculo CHECK (email = lower(email)),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('GERENTE', 'ANALISTA', 'AUDITOR'))
);

-- Usuário inicial: dados vêm do .env (ADMIN_NOME, ADMIN_EMAIL, ADMIN_SENHA) via placeholders do Flyway.
DO $$
BEGIN
    IF length('${admin_senha}') < 8 THEN
        RAISE EXCEPTION 'ADMIN_SENHA no .env precisa ter pelo menos 8 caracteres';
    END IF;
END $$;

-- ON CONFLICT: se por algum motivo o e-mail já existir, não insere de novo nem dá erro.
INSERT INTO usuario (nome, email, senha_hash, perfil, senha_temporaria)
VALUES ('${admin_nome}', lower('${admin_email}'), crypt('${admin_senha}', gen_salt('bf', 10)), 'GERENTE', TRUE)
ON CONFLICT (email) DO NOTHING;
